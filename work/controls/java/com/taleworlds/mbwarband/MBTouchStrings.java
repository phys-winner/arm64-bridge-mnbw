    static Text inventoryTransferFailure(int result) {
        switch (result) {
            case 1: return Text.INVENTORY_SELECTION_CHANGED;
            case 2: return Text.INVENTORY_NO_FREE_SLOT;
            case 3: return Text.INVENTORY_NOT_EQUIPPABLE;
            case 4: return Text.INVENTORY_REQUIREMENTS_NOT_MET;
            case 5: return Text.INVENTORY_UNSUPPORTED_TARGET;
            case 6: return Text.INVENTORY_TRANSFER_REJECTED;
            default: return null;
        }
    }

    static {
        if (CODES.length != DISPLAY_NAMES.length || CODES.length != STRINGS.length) {
            throw new AssertionError("touch language table dimensions differ");
        }
        for (int language = 0; language < STRINGS.length; ++language) {
            if (STRINGS[language].length != Text.values().length) {
                throw new AssertionError("incomplete touch strings for " + CODES[language]);
            }
        }
    }

    private MBTouchStrings() {
    }

    public static boolean isSupported(String code) {
        if (code == null) return false;
        for (String candidate : CODES) {
            if (candidate.equals(code)) return true;
        }
        return false;
    }

    public static String normalize(String code) {
        return isSupported(code) ? code : DEFAULT_CODE;
    }

    /** Maps a BCP-47 tag (or an engine code) onto the languages the engine ships. */
    public static String normalizeBcp47(String tag) {
        if (tag == null) return DEFAULT_CODE;
        if (isSupported(tag)) return tag;
        String lowered = tag.toLowerCase(Locale.ROOT);
        String language = lowered.split("[-_]")[0];
        if ("cs".equals(language)) return "cz";
        if ("zh".equals(language)) {
            if (lowered.contains("hant") || lowered.contains("tw")
                    || lowered.contains("hk") || lowered.contains("mo")) {
                return "cnt";
            }
            return "cns";
        }
        return isSupported(language) ? language : DEFAULT_CODE;
    }

    public static int indexOf(String code) {
        String normalized = normalize(code);
        for (int index = 0; index < CODES.length; ++index) {
            if (CODES[index].equals(normalized)) return index;
        }
        throw new AssertionError("default touch language is absent");
    }

    public static String codeAt(int index) {
        return index >= 0 && index < CODES.length ? CODES[index] : DEFAULT_CODE;
    }

    public static String[] codes() {
        return CODES.clone();
    }

    public static String[] displayNames() {
        return DISPLAY_NAMES.clone();
    }

    public static String get(String code, Text text) {
        if (text == null) throw new IllegalArgumentException("text must not be null");
        return STRINGS[indexOf(code)][text.ordinal()];
    }
